"""ASU quotient graphs at chain and residue resolution: covalent bonds and stitching.

Port of NAtopo's ``asu_quotient.py`` and ``residue_quotient.py`` (the two
folded-ASU views of ``main_NAtopo.ipynb``), restricted to covalent bonds and
TopoStich's stitched joins, and without NetworkX, NumPy or Bokeh.

Every node is a chain/TER segment (chain resolution) or a residue (residue
resolution) of the original asymmetric unit. Every edge is one symmetry orbit
of joins: X -> Y labelled with the symmetry code ``op_(k,l,m)`` of the
partner copy: the operation number, then a signed whole-cell shift along a, b
and c (``2_(0,+1,0)`` = operation 2, then +1 cell along b; ``1_(0,0,0)`` =
inside the ASU). The JSON also keeps the PDB form (``op_klm``, each shift + 5:
``2_565``, ``1_555``) as ``pdb_symmetry_code``. Joins with another copy of the same chain or residue are self-loops.
Composing the codes around a cycle gives the operation the lattice path ends
on. The periodicity summary uses NAtopo's voltage-graph method: for each
connected part, the rank of the lattice translations generated by its cycles
(0 finite, 1 rod, 2 layer, 3 framework) and, for 3-periodic parts, the number
of interpenetrating copies.

Edge types:

* ``covalent`` - consecutive O3'-P polymer links in a segment (0.8-2.2 A) and
  deposited links between residues at 0.8-2.3 A with no metal or hydrogen
  endpoint: mmCIF _struct_conn of a covalent type (covale*, disulf; never
  hydrog or metalc) or untyped PDB CONECT. Symmetry-image links are not read.
* ``backbone_join``, ``backbone_join_o5`` - stitched nick joins.
* ``terminal_stack`` - stitched chain-end pi stacks, with their end polarity.

Nodes are the nucleotide residues (those with backbone atoms) plus any
non-water residue joined to the graph by a deposited covalent link.
"""
from __future__ import annotations

from collections import Counter, defaultdict
from fractions import Fraction
import math

import gemmi

from .converter import covalent_connections, normalized_name

GRID = 24  # Space-group translations lie on the 1/24 fractional grid.
EDGE_TYPES = ('covalent', 'backbone_join', 'backbone_join_o5', 'terminal_stack')
EDGE_LABELS = {'covalent': 'Covalent bond', 'backbone_join': "Stitched backbone join (P...O3')",
               'backbone_join_o5': "Stitched O5'...O3' join (phosphate missing)",
               'terminal_stack': 'Stitched chain-end pi stack'}
WATER = {'HOH', 'WAT', 'DOD', 'H2O', 'D2O'}
COVALENT_ELEMENTS = {'B', 'C', 'N', 'O', 'F', 'SI', 'P', 'S', 'CL', 'SE', 'BR', 'I'}
EXPLICIT_COVALENT_A = (0.8, 2.3)
DIMENSION_WORDS = {0: 'finite (0-periodic)', 1: '1-periodic rod/chain', 2: '2-periodic layer',
                   3: '3-periodic framework'}


# ------------------------------------------------------------------ symmetry algebra
# An operation is (R, t): integer rotation rows and translation in 1/GRID units.

def from_gemmi(op):
    return tuple(tuple(v // GRID for v in row) for row in op.rot), tuple(op.tran)


def to_gemmi(g):
    op = gemmi.Op('x,y,z')
    op.rot = [[GRID*v for v in row] for row in g[0]]
    op.tran = list(g[1])
    return op


IDENTITY = ((1, 0, 0), (0, 1, 0), (0, 0, 1)), (0, 0, 0)


def _mat_mul(a, b):
    return tuple(tuple(sum(a[i][k]*b[k][j] for k in range(3)) for j in range(3)) for i in range(3))


def _mat_vec(a, v):
    return tuple(sum(a[i][k]*v[k] for k in range(3)) for i in range(3))


def _det(m):
    return (m[0][0]*(m[1][1]*m[2][2]-m[1][2]*m[2][1]) - m[0][1]*(m[1][0]*m[2][2]-m[1][2]*m[2][0])
            + m[0][2]*(m[1][0]*m[2][1]-m[1][1]*m[2][0]))


def compose(g, h):
    """(R1,t1)(R2,t2) = (R1R2, R1t2 + t1)."""
    return _mat_mul(g[0], h[0]), tuple(a+b for a, b in zip(_mat_vec(g[0], h[1]), g[1]))


def inverse(g):
    m = g[0]
    det = _det(m)
    adj = [[m[(j+1) % 3][(i+1) % 3]*m[(j+2) % 3][(i+2) % 3] - m[(j+1) % 3][(i+2) % 3]*m[(j+2) % 3][(i+1) % 3]
            for j in range(3)] for i in range(3)]
    r = tuple(tuple(v // det for v in row) for row in adj)
    return r, tuple(-v for v in _mat_vec(r, g[1]))


def key(g):
    return (*(v for row in g[0] for v in row), *g[1])


def format_shift(n):
    """Signed cell shift for labels: [1, -1, 0] -> '(+1,-1,0)'."""
    return '(' + ','.join(f'{v:+d}' if v else '0' for v in n) + ')'


def pdb_symmetry_code(op_id, n):
    """PDB 'op_klm' (each shift + 5), or 'op(k, l, m)' when a shift is beyond +-4."""
    return (f"{op_id}_{''.join(str(5+v) for v in n)}" if all(-4 <= v <= 4 for v in n)
            else f'{op_id}{tuple(n)}')


def symmetry_code(g, operations):
    """Name operation g as 'op_(k,l,m)' (signed cell shifts) relative to numbered operations.

    operations: [(id, (R, t))]. Returns (code, operator id, lattice translation).
    """
    for op_id, (rotation, translation) in operations:
        if rotation != g[0]:
            continue
        shift = [a-b for a, b in zip(g[1], translation)]
        if all(v % GRID == 0 for v in shift):
            n = [v // GRID for v in shift]
            return f'{op_id}_{format_shift(n)}', str(op_id), n
    raise ValueError('Relative operation does not match any listed symmetry operation')


def _hermite_basis(vectors):
    """Integer row-echelon (Hermite normal form) basis of the lattice spanned by vectors."""
    rows = [list(map(int, v)) for v in vectors if any(v)]
    basis, column = [], 0
    while rows and column < 3:
        rows = [r for r in rows if any(r)]
        if not any(r[column] for r in rows):
            column += 1
            continue
        while sum(1 for r in rows if r[column]) > 1:  # Euclid on the pivot column.
            small = min((r for r in rows if r[column]), key=lambda r: abs(r[column]))
            reduced = [small]
            for r in rows:
                if r is small:
                    continue
                if r[column]:
                    q = r[column] // small[column]
                    r = [a - q*c for a, c in zip(r, small)]
                reduced.append(r)
            rows = [r for r in reduced if any(r)]
        pivot = next(r for r in rows if r[column])
        if pivot[column] < 0:
            pivot = [-v for v in pivot]
        basis.append((column, pivot))
        rows = [r for r in rows if not r[column]]
        column += 1
    for i, (column, pivot) in enumerate(basis):  # Reduce entries above each pivot.
        for j in range(i):
            row = basis[j][1]
            factor = row[column] // pivot[column]
            basis[j] = (basis[j][0], [x - factor*y for x, y in zip(row, pivot)])
    return [row for _, row in basis]


def generated_translations(generators):
    """(Translation basis x GRID, point-group order) of the subgroup generated by generators."""
    reps = {IDENTITY[0]: IDENTITY}
    translations, queue = [], [IDENTITY]
    gens = list(generators) + [inverse(g) for g in generators]
    while queue:
        element = queue.pop()
        for g in gens:
            product = compose(element, g)
            if product[0] not in reps:
                reps[product[0]] = product
                queue.append(product)
            else:
                difference = compose(product, inverse(reps[product[0]]))  # (I, dt)
                if any(difference[1]):
                    translations.append(difference[1])
    closed = [_mat_vec(r, t) for r, _ in reps.values() for t in translations]
    return _hermite_basis(closed), len(reps)


def _format_vector(v):
    parts = []
    for x in v:
        f = Fraction(int(x), GRID)
        parts.append(str(f.numerator) if f.denominator == 1 else f'{f.numerator}/{f.denominator}')
    return f"[{', '.join(parts)}]"


def periodicity(node_ids, edges, operations):
    """Per connected part: generated lattice translations, their rank and copies.

    edges: dicts with source, target and operation (R, t) mapping target's copy.
    """
    order = {n: i for i, n in enumerate(node_ids)}
    adjacency = defaultdict(list)
    for e in edges:
        adjacency[e['source']].append((e['target'], e['operation']))
        adjacency[e['target']].append((e['source'], inverse(e['operation'])))
    rotations = {r for _, (r, _) in operations}
    lattice = [[GRID if i == j else 0 for j in range(3)] for i in range(3)]
    lattice += [list(t) for _, (r, t) in operations if r == IDENTITY[0]]
    full_volume = abs(_det(_hermite_basis(lattice)))
    seen, results = set(), []
    parts = []
    for root in node_ids:
        if root in seen:
            continue
        potential, queue = {root: IDENTITY}, [root]
        seen.add(root)
        while queue:  # Breadth-first spanning tree: voltage from root to each node.
            node = queue.pop(0)
            for other, g in adjacency[node]:
                if other not in potential:
                    potential[other] = compose(potential[node], g)
                    seen.add(other)
                    queue.append(other)
        parts.append(potential)
    for potential in sorted(parts, key=lambda p: (-len(p), min(order[n] for n in p))):
        cycles = []
        for e in edges:
            if e['source'] in potential:
                cycle = compose(compose(potential[e['source']], e['operation']), inverse(potential[e['target']]))
                if key(cycle) != key(IDENTITY):
                    cycles.append(cycle)
        basis, point_order = generated_translations(cycles) if cycles else ([], 1)
        copies = None
        if len(basis) == 3:  # Index of the generated subgroup = number of disjoint nets.
            copies = round(len(rotations) / point_order * abs(_det(basis)) / full_volume)
        results.append(dict(nodes=sorted(potential, key=order.get), dimension=len(basis),
                            translation_basis=[_format_vector(v) for v in basis],
                            point_group_order=point_order, space_group_point_order=len(rotations),
                            interpenetrating_copies=copies, independent_cycles=len(cycles)))
    return results


def describe_periodicity(graph, *, resolution):
    """NAtopo's one-line-per-part summary; residues are counted per chain."""
    labels = {n['id']: n for n in graph['nodes']}
    lines, isolated = [], []
    for part in graph['periodicity']:
        if part['dimension'] == 0 and len(part['nodes']) == 1:
            isolated.append(labels[part['nodes'][0]]['label'])
            continue
        if resolution == 'chain':
            names = ', '.join(labels[n]['label'] for n in part['nodes'])
        else:
            counts = Counter(labels[n]['chain_label'] for n in part['nodes'])
            names = ', '.join(f'{c} ({k})' for c, k in counts.items()) + ' residues'
        extra = f" along {' & '.join(part['translation_basis'])}" if part['translation_basis'] else ''
        copies = part['interpenetrating_copies']
        nets = f'; {copies} interpenetrating copies of this net' if copies and copies > 1 else ''
        lines.append(f"{names}: {DIMENSION_WORDS[part['dimension']]}{extra}{nets}")
    if isolated:
        shown = ', '.join(isolated[:6]) + (f' ... (+{len(isolated) - 6})' if len(isolated) > 6 else '')
        noun = 'node(s)' if resolution == 'chain' else 'residue(s)'
        lines.append(f'{len(isolated)} single {noun} with no join, finite: {shown}')
    return lines


# --------------------------------------------------------------------- graph building

def numbered_operations(pdb, operations):
    """[(id, (R, t))] using the input's operator numbering when it has one."""
    if pdb.symops:
        return [(i, from_gemmi(gemmi.Op(op))) for i, op in sorted(pdb.symops.items())]
    return [(i, from_gemmi(op)) for i, op in enumerate(operations, 1)]


def _deposited_covalent(ctx):
    """[(residue a, residue b, atom a, atom b, distance)] from CONECT/_struct_conn."""
    by_serial = {}
    for atom in ctx.pdb.atoms:
        if ctx.altloc is None or atom.altloc in ('', ctx.altloc):
            by_serial.setdefault(atom.serial, atom)
    links, seen = [], set()
    for left, right in covalent_connections(ctx.pdb):
        a, b = by_serial.get(left), by_serial.get(right)
        if a is None or b is None or a.residue_key == b.residue_key:
            continue
        if a.residue.upper() in WATER or b.residue.upper() in WATER:
            continue
        if a.element.upper() not in COVALENT_ELEMENTS or b.element.upper() not in COVALENT_ELEMENTS:
            continue
        d = math.dist(a.xyz, b.xyz)
        if not EXPLICIT_COVALENT_A[0] <= d <= EXPLICIT_COVALENT_A[1]:
            continue
        token = frozenset((a.serial, b.serial))
        if token not in seen:
            seen.add(token)
            links.append((a.residue_key, b.residue_key, a, b, d))
    return links


def _atom_text(chain_label, atom):
    return f'{chain_label}:{atom.residue}{atom.seq}{atom.insertion} {normalized_name(atom.name)}'


def _orient(order, s, t, g):
    forward, backward = (s, t, g), (t, s, inverse(g))
    return min(forward, backward, key=lambda e: (order[e[0]], order[e[1]], key(e[2])))


def _edge_record(source, target, g, kind, operations):
    code, op_id, shift = symmetry_code(g, operations)
    return dict(source=source, target=target, type=kind, symmetry_code=code,
                pdb_symmetry_code=pdb_symmetry_code(op_id, shift), operator=op_id,
                lattice_translation=shift, operation=to_gemmi(g).triplet(), intra_asu=key(g) == key(IDENTITY),
                distance_min_A=None, distance_max_A=None)


def build_asu_graphs(ctx, operations, *, name, space_group):
    """Return {'chain': graph, 'residue': graph}; see the module docstring."""
    deposited = _deposited_covalent(ctx)
    nucleotides = set(ctx.nucleotide)
    included = set(nucleotides)
    for a, b, *_ in deposited:
        included.update((a, b))
    keys = [k for k in ctx.order if k in included]
    segments = list(dict.fromkeys(k[0] for k in keys))
    seg_keys = {s: [k for k in keys if k[0] == s] for s in segments}
    first_atom = {k: next(a for a in ctx.all_atoms[k].values() if a is not None) for k in keys}

    # Chain labels: author chain ID, disambiguated when segments share it.
    base = {s: first_atom[seg_keys[s][0]].chain or '.' for s in segments}
    shared = Counter(base.values())
    chain_label = {}
    for s in segments:
        atom = first_atom[seg_keys[s][0]]
        if shared[base[s]] == 1:
            chain_label[s] = base[s]
        elif atom.label_asym and atom.label_asym != base[s]:
            chain_label[s] = f'{base[s]}/{atom.label_asym}'
        else:
            chain_label[s] = f'{base[s]}/S{s}'
    kind_of = {s: 'polymer' if sum(k in nucleotides for k in seg_keys[s]) >= 2 else 'other' for s in segments}
    rid = {k: f'S{k[0]}:{k[4]}{k[2]}{k[3]}#{k[5]}' if k[5] else f'S{k[0]}:{k[4]}{k[2]}{k[3]}' for k in keys}
    rlabel = {k: f'{chain_label[k[0]]}:{k[4]}{k[2]}{k[3]}' for k in keys}

    residue_nodes = []
    for s in segments:
        for position, k in enumerate(seg_keys[s]):
            atom = first_atom[k]
            residue_nodes.append(dict(id=rid[k], label=rlabel[k], residue=k[4], seq=k[2], insertion=k[3],
                                      chain=atom.chain, label_asym=atom.label_asym, segment=s,
                                      chain_node=f'S{s}', chain_label=chain_label[s], kind=kind_of[s],
                                      position_in_chain=position))
    chain_nodes = [dict(id=f'S{s}', label=chain_label[s], chain=base[s] if base[s] != '.' else '',
                        label_asym=first_atom[seg_keys[s][0]].label_asym, segment=s, kind=kind_of[s],
                        residue_count=len(seg_keys[s]), internal_covalent_edges=0) for s in segments]

    # Raw residue-level joins: (a, b, g, type, contact).
    raw = []
    for left, right, o3, p in ctx.polymer_links:
        d = math.dist(o3.xyz, p.xyz)
        raw.append((left, right, IDENTITY, 'covalent',
                    dict(text=f"{_atom_text(chain_label[left[0]], o3)} - {_atom_text(chain_label[right[0]], p)} {d:.2f} A",
                         distance_A=d)))
    for a, b, atom_a, atom_b, d in deposited:
        raw.append((a, b, IDENTITY, 'covalent',
                    dict(text=f"{_atom_text(chain_label[a[0]], atom_a)} - {_atom_text(chain_label[b[0]], atom_b)} "
                              f"{d:.2f} A (deposited)", distance_A=d)))
    for link in ctx.stitched_links:
        a, b, g = link['a'], link['b'], from_gemmi(link['g'])
        if a not in included or b not in included:
            continue
        kind = 'covalent' if link['kind'] == 'deposited_link' else link['kind']
        ev = link['evidence']
        if kind == 'terminal_stack':
            contact = dict(text=f"{rlabel[a]} ({ev['source_end']} end) stacks on {rlabel[b]} ({ev['target_end']} end), "
                                f"centroids {link['distance']:.2f} A, polarity {ev['polarity']}",
                           distance_A=link['distance'], polarity=ev['polarity'], same_polarity=ev['same_polarity'])
        else:
            contact = dict(text=f"{rlabel[a]} {ev['o3_atom']['atom']} ... {rlabel[b]} {ev['p_atom']['atom']} "
                                f"{link['distance']:.2f} A (stitched)", distance_A=link['distance'])
        raw.append((a, b, g, kind, contact))

    graphs = {}
    # Residue resolution.
    order = {rid[k]: i for i, k in enumerate(k for s in segments for k in seg_keys[s])}
    merged = {}
    for a, b, g, kind, contact in raw:
        s, t, g2 = _orient(order, rid[a], rid[b], g)
        token = (s, t, key(g2), kind)
        if token not in merged:
            merged[token] = dict(_edge_record(s, t, g2, kind, operations), _g=g2, contacts=[])
            same_chain = s.split(':')[0] == t.split(':')[0] and key(g2) == key(IDENTITY)
            merged[token]['intra_chain'] = same_chain
        if contact['text'] not in [c['text'] for c in merged[token]['contacts']]:
            merged[token]['contacts'].append(contact)
    graphs['residue'] = _finish(residue_nodes, list(merged.values()), operations, name, space_group, 'residue')

    # Chain resolution.
    corder = {f'S{s}': i for i, s in enumerate(segments)}
    internal = Counter()
    merged = {}
    for a, b, g, kind, contact in raw:
        ca, cb = f'S{a[0]}', f'S{b[0]}'
        if ca == cb and key(g) == key(IDENTITY):
            internal[ca] += 1
            continue
        s, t, g2 = _orient(corder, ca, cb, g)
        token = (s, t, key(g2), kind)
        if token not in merged:
            merged[token] = dict(_edge_record(s, t, g2, kind, operations), _g=g2, residue_pairs=[],
                                 residue_edge_count=0, contacts=[])
        pair = ' <-> '.join(sorted((rlabel[a], rlabel[b])))
        if 'polarity' in contact:
            pair += f" ({contact['polarity']})"
        entry = merged[token]
        if pair not in entry['residue_pairs']:
            entry['residue_pairs'].append(pair)
            entry['residue_edge_count'] += 1
        entry['contacts'].append(contact)
    for node in chain_nodes:
        node['internal_covalent_edges'] = internal[node['id']]
    graphs['chain'] = _finish(chain_nodes, list(merged.values()), operations, name, space_group, 'chain')
    return graphs


def _finish(nodes, edges, operations, name, space_group, resolution):
    for e in edges:
        contacts = e.pop('contacts')
        distances = [c['distance_A'] for c in contacts]
        e['distance_min_A'], e['distance_max_A'] = min(distances), max(distances)
        if e['type'] == 'terminal_stack':
            e['polarities'] = sorted({c['polarity'] for c in contacts})
            e['same_polarity'] = any(c['same_polarity'] for c in contacts)
        if resolution == 'residue':
            e['contacts'] = [c['text'] for c in contacts]
    order = {n['id']: i for i, n in enumerate(nodes)}
    edges.sort(key=lambda e: (order[e['source']], order[e['target']], not e['intra_asu'], e['symmetry_code'], e['type']))
    parts = periodicity([n['id'] for n in nodes],
                        [dict(source=e['source'], target=e['target'], operation=e['_g']) for e in edges], operations)
    for e in edges:
        del e['_g']
    graph = dict(resolution=resolution, name=name, space_group=space_group, nodes=nodes, edges=edges,
                 edge_type_counts=dict(sorted(Counter(e['type'] for e in edges).items())),
                 self_loops=sum(e['source'] == e['target'] for e in edges),
                 symmetry_edges=sum(not e['intra_asu'] for e in edges), periodicity=parts)
    graph['summary'] = describe_periodicity(graph, resolution=resolution)
    return graph
